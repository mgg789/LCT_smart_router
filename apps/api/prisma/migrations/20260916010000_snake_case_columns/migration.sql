-- Column names to snake_case.
--
-- Table names were already snake_case while columns kept their Prisma spelling, which
-- left the schema half in one convention and half in the other. That matters beyond
-- tidiness: Router Core reads the published sector directly, from Python, and an
-- unquoted `SELECT inputHash` there folds to `inputhash` and fails. Requiring every
-- cross-language query to quote a camelCase identifier is a trap, so the columns are
-- renamed while the migration history is still two files long.
--
-- RENAME COLUMN rather than drop and create: a rename preserves the data, and a
-- migration that silently emptied a column would be a far worse habit to establish.
--
-- Grants are on tables and are unaffected.

